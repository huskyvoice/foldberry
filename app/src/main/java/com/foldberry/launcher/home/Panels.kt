package com.foldberry.launcher.home

/*
 * ホームで開くパネルと、「戻る」で閉じる順(仕様書 §5.3)。
 * Android 非依存にして単体テストで検証する(PanelsTest)。状態そのものは ui/HomeController が持つ。
 */

/** 開いているパネルの種類。宣言順 = 「戻る」で先に閉じる順(手前に重なっているものから)。 */
enum class Panel {
    /** 音声操作のカード(0 のキーの長押し。§5.5。D27)。いちばん手前に出るので最初に閉じる(閉じる=中止) */
    VOICE,

    /** 設定シート(BBメニュー。§8)。読込みの確認待ちを含む */
    SETTINGS,

    /** 割り当てシート(キー・枠の長押し。§7) */
    ASSIGN,

    /** アプリ一覧の長押しメニュー(§6) */
    APP_MENU,

    /**
     * カバー構成のアプリ一覧の重ね表示(トラックパッド。§5.3)。
     * キーの選択待ち中にトラックパッドで重ねた場合は、見えている一覧を先に閉じて選択待ちに戻す。
     */
    APP_OVERLAY,

    /**
     * メイン構成の一覧の枠に出したアプリ一覧(トラックパッド。§4.5)。普段はカレンダー+自由枠で、閉じるとそこに戻る。
     * 長押しメニューはこの上に出るので先に閉じる。選択待ちより手前(重ね表示と同じ扱い)。
     */
    MAIN_LIST,

    /**
     * メイン構成の一覧の枠に開いた自由枠のフォルダ(§4.5。v0.7.1)。一覧(MAIN_LIST)とは同時に開かない。
     * 割り当てシート(フォルダの編集)はこの上に出るので先に閉じる。
     */
    FOLDER,

    /** 「キーに割り当て」でキーが押されるのを待っている状態(§6)。重ね表示の下の本体に帯を出している */
    KEY_PICK,
}

/** 「戻る」で閉じるパネル。何も開いていなければ null(何もしない。§5.3)。 */
fun panelToClose(open: Set<Panel>): Panel? = Panel.entries.firstOrNull { it in open }
